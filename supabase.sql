-- Run in Supabase SQL Editor. Admin authorization is enforced by RLS, NOT the 123 UI PIN.
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null,
 price numeric(10,2) not null check(price>=0),
 offer_price numeric(10,2) check(offer_price>=0),
 media_url text not null,
 media_type text not null default 'image' check(media_type in ('image','video')),
 available boolean not null default true,
 sort_order integer not null default 0,
 created_at timestamptz default now()
);
create table if not exists public.site_settings (
 id integer primary key default 1 check(id=1),
 phone text not null default '9898221813',
 instagram text not null default 'https://www.instagram.com/fashioncorner5866',
 about text not null default 'Beautiful outfits at affordable prices. Surat-Kamrej, Gujarat.'
);
insert into public.site_settings(id) values(1) on conflict(id) do nothing;
create or replace function public.is_fc_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_users where user_id=(select auth.uid()));
$$;
alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.site_settings enable row level security;
create policy "Admin reads own membership" on public.admin_users for select to authenticated using(user_id=(select auth.uid()));
create policy "Public read products" on public.products for select to anon,authenticated using(true);
create policy "Admin insert products" on public.products for insert to authenticated with check(public.is_fc_admin());
create policy "Admin update products" on public.products for update to authenticated using(public.is_fc_admin()) with check(public.is_fc_admin());
create policy "Admin delete products" on public.products for delete to authenticated using(public.is_fc_admin());
create policy "Public read settings" on public.site_settings for select to anon,authenticated using(true);
create policy "Admin insert settings" on public.site_settings for insert to authenticated with check(public.is_fc_admin());
create policy "Admin update settings" on public.site_settings for update to authenticated using(public.is_fc_admin()) with check(public.is_fc_admin());
